test("explicit exit observes grace and targets only its status", function()
  local h = start({ bottom_pane = { close_grace_seconds = 2 } })
  h:shell()
  h:tick(1)
  h:tick(1)
  eq(#h.close_commands, 0)
  h:tick(1)
  eq(#h.close_commands, 1)
