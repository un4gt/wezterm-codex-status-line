local fake = require("tests.fake_wezterm")
local layout = require("codex_statusline.layout")
local count = 0
local function eq(a, b, label) assert(a == b, (label or "comparison") .. ": " .. tostring(a) .. " ~= " .. tostring(b)) end
local function test(name, fn)
  fn()
  count = count + 1
  print("PASS " .. name)
end
local function start(options)
  local h = fake.new(options)
  h:start()
  h:settle()
  assert(h:status(), table.concat(h.logs, "\n"))
  return h
end

test("local status preserves right pane and focus", function()
  local h = fake.new()
  local right = h:split(h.main)
  local height = right.dimensions.viewport_rows
  h:start()
  h:settle()
  assert(h:status())
  eq(h:status().dimensions.cols, h.main.dimensions.cols)
  eq(right.dimensions.viewport_rows, height)
  eq(h.tab:active_pane(), right)
  eq(h.splits[2].args.top_level, false)
  h:settle()
  eq(#h.close_commands, 0)
  h:assert_no_errors()
end)

test("two Codex owners do not close each other's status", function()
  local h = fake.new()
  local right = h:split(h.main)
  h:start()
  h:start(right)
  h:settle()
  h:settle()
  assert(h:status() and h:status(right))
  assert(h:status() ~= h:status(right))
  h:shell(right)
  h:settle()
  eq(h.close_commands[1][6], tostring(h:status(right).id))
  h:complete_close(1)
  h:settle()
  assert(h:status())
  eq(h:status(right), nil)
  h:assert_no_errors()
end)

test("split after status defers repair without changing user geometry", function()
  local h = start()
  local status = h:status()
  h:split(h.main)
  local signature = layout.signature(h.tab:panes_with_info())
  h:settle()
  h:settle()
  eq(h:status(), status)
  eq(layout.signature(h.tab:panes_with_info()), signature)
  eq(#h.close_commands, 0)
  eq(h:binding().deferred, "preserve-user-layout")
end)

test("debounce restarts on every changed layout", function()
  local h = fake.new()
